CREATE TYPE enrollment_status AS ENUM ('active', 'completed', 'cancelled');
CREATE TYPE submission_status AS ENUM ('submitted', 'graded');

CREATE TABLE roles (
    id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) UNIQUE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE users (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255) UNIQUE NOT NULL,
    full_name  VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    updated_by INT,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ,
    deleted_by INT
);

CREATE TABLE user_roles (
    user_id INT NOT NULL,
    role_id INT NOT NULL,
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE courses (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    description TEXT,
    category    VARCHAR(100) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ,
    updated_by  INT,
    is_deleted  BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at  TIMESTAMPTZ,
    deleted_by  INT
);

CREATE TABLE course_instructors (
    course_id     INT NOT NULL,
    instructor_id INT NOT NULL,
    PRIMARY KEY (course_id, instructor_id)
);

CREATE TABLE modules (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id  INT NOT NULL,
    title      VARCHAR(200) NOT NULL,
    position   INT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ,
    deleted_by INT
);

CREATE TABLE lessons (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id  INT NOT NULL,
    title      VARCHAR(200) NOT NULL,
    content    TEXT,
    position   INT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    updated_by INT,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ,
    deleted_by INT
);

CREATE TABLE enrollments (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  INT NOT NULL,
    course_id   INT NOT NULL,
    status      enrollment_status NOT NULL DEFAULT 'active',
    enrolled_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE lesson_progress (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id INT NOT NULL,
    lesson_id     INT NOT NULL,
    is_completed  BOOLEAN NOT NULL DEFAULT FALSE,
    completed_at  TIMESTAMPTZ
);

CREATE TABLE assignments (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id  INT NOT NULL,
    title      VARCHAR(200) NOT NULL,
    max_score  INT NOT NULL DEFAULT 100 CHECK (max_score > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE submissions (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id INT NOT NULL,
    student_id    INT NOT NULL,
    answer_text   TEXT,
    status        submission_status NOT NULL DEFAULT 'submitted',
    submitted_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ,
    updated_by    INT
);

CREATE TABLE grades (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id INT UNIQUE NOT NULL,
    grader_id     INT NOT NULL,
    score         DECIMAL(5,2) NOT NULL CHECK (score >= 0),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ,
    updated_by    INT
);

CREATE TABLE quizzes (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id  INT NOT NULL,
    title      VARCHAR(200) NOT NULL,
    pass_score INT NOT NULL DEFAULT 60 CHECK (pass_score BETWEEN 0 AND 100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE quiz_questions (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id       INT NOT NULL,
    question_text TEXT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE answer_options (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id INT NOT NULL,
    option_text TEXT NOT NULL,
    is_correct  BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE reviews (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id  INT NOT NULL,
    student_id INT NOT NULL,
    rating     INT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment    TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

