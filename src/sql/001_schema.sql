CREATE UNIQUE INDEX uq_lessons_module_position ON lessons (module_id, position) WHERE is_deleted = FALSE;
CREATE UNIQUE INDEX uq_enrollments_student_course ON enrollments (student_id, course_id);
CREATE UNIQUE INDEX uq_progress_enrollment_lesson ON lesson_progress (enrollment_id, lesson_id);
CREATE UNIQUE INDEX uq_submissions_assign_student ON submissions (assignment_id, student_id);
CREATE UNIQUE INDEX uq_reviews_course_student ON reviews (course_id, student_id);

